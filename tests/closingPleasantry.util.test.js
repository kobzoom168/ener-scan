/**
 * ข้อความปิดบท = เงียบ (กบ 18 ส.ค.): ขอบคุณ/ครับ/โชคดี/สาธุ ไม่ต้องตอบ
 * จนกว่าลูกค้าจะส่งเรื่องใหม่ — คำถาม/ชื่อพระ/เรื่องเงินห้ามโดนเงียบ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { isClosingPleasantry } from "../src/core/conversation/closingPleasantry.util.js";

test("คำปิดบท = true", () => {
  for (const t of [
    "ขอบคุณ", "ขอบคุณครับ", "ขอบคุณมากๆครับ", "ขอบพระคุณครับ",
    "ครับ", "ครับผม", "โอเค", "โอเคครับ", "ok", "Thanks",
    "โชคดีครับ", "ราตรีสวัสดิ์", "ฝันดีนะครับ", "บาย",
    "สาธุ", "สาธุครับ", "อนุโมทนาสาธุ", "🙏", "🙏🙏",
  ]) {
    assert.equal(isClosingPleasantry(t), true, `"${t}" ควรเงียบ`);
  }
});

test("เรื่องจริงห้ามโดนเงียบ", () => {
  for (const t of [
    "ขอบคุณครับ แล้วองค์นี้แขวนคอได้ไหม", // มีคำถามพ่วง
    "ผลออกยัง", "จ่าย 49", "ประวัติ", "จัดชุด",
    "พระสมเด็จวัดระฆัง", "เปลี่ยนวันเกิด", "สวัสดีครับ อยากถามเรื่องพระ",
    "ขอบคุณที่ช่วยดูให้ แต่ทำไมคะแนนต่ำจัง",
  ]) {
    assert.equal(isClosingPleasantry(t), false, `"${t}" ต้องไม่โดนเงียบ`);
  }
});
