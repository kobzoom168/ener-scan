/**
 * คำสั่ง/คำถามเรื่องแจ้งเตือนหนุนดวงรายเช้า — แยกไฟล์เพื่อทดสอบได้โดยไม่ต้องโหลด webhook
 *
 * กติกา (Codex 17 ก.ย.): **คำถามไม่เปลี่ยนค่า · คำสั่งชัดเจนจึงเปลี่ยนค่า**
 *   "หยุดแจ้งเตือน" / "ปิดเตือน" / "ยกเลิกแจ้งเตือน" → off  (เปลี่ยนค่า)
 *   "เปิดแจ้งเตือน" / "เปิดเตือน"                     → on   (เปลี่ยนค่า)
 *   "ปิดแจ้งเตือนยังไง" / "รับเตือน" / "อย่าปิดแจ้งเตือน" → help (ตอบวิธีแบบ deterministic
 *     ไม่แตะค่า และไม่ปล่อยให้ AI ไปสัญญาว่า "ปิดให้แล้ว" ทั้งที่ไม่ได้บันทึกอะไร)
 *
 * รอบแก้ 17 ก.ย. 2026 (หลัง live test บน staging): เดิมบังคับว่าต้องมีคำว่า "แจ้งเตือน" เต็ม ๆ
 * → ลูกค้าพิมพ์ "ปิดเตือน" หลุดไปหา AI แล้ว AI ตอบ "ครับ ปิดให้แล้วครับ" โดยไม่บันทึกค่าเลย
 * (ของจริง 05:50:18Z replyType=gemini_front_consult และไม่มี DAILY_PICK_OPTOUT_SAVED ตามมา)
 *
 * วิธีกันการจับผิด: **ไม่ใช้ substring** — ข้อความต้องมีรูปคำสั่งครบทั้งประโยค (anchored)
 * ประโยคยาวที่บังเอิญมีคำว่า "เตือน" อยู่ข้างในจึงไม่เข้าเส้นนี้
 */

/** คำลงท้ายสุภาพที่ไม่เปลี่ยนความหมายของคำสั่ง */
const POLITE_TAIL = /(ครับ|ค่ะ|คะ|ฮะ|จ้า|จ้ะ|นะ|น่ะ|หน่อย|ที|ด้วย|เลย|ให้)+$/u;
/** คำนำหน้าสุภาพ */
const POLITE_HEAD = /^(ขอ|รบกวน|ช่วย|ฝาก)+/u;

const QUESTION_HINT =
  /(ยังไง|อย่างไร|ไง|ทำไง|ทำยังไง|วิธี|ได้ไหม|ได้มั้ย|ยัง|เหรอ|หรอ|มั้ย|ไหม|\?|？)/u;

/** ปฏิเสธ/ห้าม — "อย่าปิดแจ้งเตือน" ไม่ใช่คำสั่งปิด */
const NEGATION = /(อย่า|ไม่ต้อง|ห้าม|ยังไม่|ไม่อยาก|ไม่ได้อยาก)/u;

/** อ้างคำพูด — `พิมพ์ว่า "หยุดแจ้งเตือน"` ไม่ใช่การสั่งปิด */
const QUOTE_MARK = /["'“”‘’«»「」『』]/u;
const REPORTING_VERB = /(พิมพ์|บอกว่า|เขียนว่า|ส่งคำว่า|คำว่า|ข้อความว่า|กดว่า)/u;

/** คำนามที่บ่งชี้ว่าเป็นเรื่อง "การแจ้งเตือนของบริการ" ชัดเจน (ประตู intent) */
const NOTIFY_NOUN = /(แจ้งเตือน|การเตือน|ข้อความเตือน|เตือนหนุนดวง|เตือนตอนเช้า)/u;

/** คำนามเป้าหมาย + ส่วนขยาย เช่น "แจ้งเตือนตอนเช้า" */
const NOUN = "(?:การ)?(?:ข้อความ)?(?:แจ้ง)?เตือน(?:หนุนดวง|ตอนเช้า|รายวัน|ประจำวัน|เช้า|ทุกเช้า)?";

/** กริยาที่แปลว่า "หยุดส่ง" — ครอบคลุมภาษาที่ลูกค้าใช้จริง */
const OFF_VERB = "(?:ปิด|หยุด|ยกเลิก|เอาออก|ไม่รับ|ไม่เอา|งด|ไม่ส่ง)";
/** กริยาที่แปลว่า "ขอรับอีกครั้ง" แบบไม่กำกวม */
const ON_VERB = "(?:เปิด|กลับมารับ|อยากรับ|ขอรับ)";
/** กำกวม: "รับเตือน" อาจเป็นการพูดลอย ๆ → help ก่อน ห้ามเปิดเอง */
const AMBIGUOUS_ON_VERB = "(?:รับ|เอา)";

const OFF_RE = new RegExp(`^${OFF_VERB}${NOUN}$`, "u");
const ON_RE = new RegExp(`^${ON_VERB}${NOUN}$`, "u");
const AMBIGUOUS_ON_RE = new RegExp(`^${AMBIGUOUS_ON_VERB}${NOUN}$`, "u");
/** กริยาที่บอกว่ากำลังพูดเรื่อง "ตั้งค่า" การแจ้งเตือน */
const SETTING_VERB = /(ปิด|หยุด|ยกเลิก|เอาออก|งด|เปิด|รับ|เอา|ส่ง)/u;

function normalize(text) {
  let t = String(text || "").trim().replace(/\s+/g, "");
  let prev = null;
  // ลอกคำสุภาพที่ซ้อนกัน เช่น "ขอปิดแจ้งเตือนหน่อยนะครับ"
  while (prev !== t) {
    prev = t;
    t = t.replace(POLITE_TAIL, "").replace(POLITE_HEAD, "");
  }
  return t;
}

/**
 * @param {string} text ข้อความดิบจากลูกค้า
 * @returns {"off"|"on"|"help"|null} null = ไม่เกี่ยวกับการตั้งค่าแจ้งเตือน ให้ไหลไปเส้นทางเดิม
 */
export function matchDailyPickNotifyCommand(text) {
  const raw = String(text || "").trim();
  const t = normalize(raw);
  if (!t) return null;

  // ประตู intent — จำกัดเฉพาะเรื่อง "ตั้งค่าการแจ้งเตือนของบริการ" เท่านั้น
  // ผ่านได้สองทาง: มีคำนามชัด ("แจ้งเตือน") คู่กับกริยาตั้งค่า หรือรูปประโยคเป็นคำสั่งเป๊ะ ("ปิดเตือน")
  // ประโยคทั่วไปที่บังเอิญมีคำว่า "เตือน" (เช่น "พระองค์นี้เตือนอะไรผมไหม") จะไม่เข้าเส้นนี้
  const commandShaped = OFF_RE.test(t) || ON_RE.test(t) || AMBIGUOUS_ON_RE.test(t);
  const settingIntent = NOTIFY_NOUN.test(t) && SETTING_VERB.test(t);
  // อ้างคำพูดที่มีคำสั่งอยู่ข้างใน เช่น `ลูกค้าบอกว่า "ปิดเตือน"` — ต้องตอบวิธีแบบ deterministic
  // ไม่ใช่ปล่อยเข้า AI (เสี่ยง AI ตอบว่าปิดให้แล้ว) และไม่ใช่ตีเป็นคำสั่งปิดจริง
  const quotedCommand =
    (QUOTE_MARK.test(raw) || REPORTING_VERB.test(raw)) &&
    new RegExp(`(?:${OFF_VERB}|${ON_VERB}|${AMBIGUOUS_ON_VERB})${NOUN}`, "u").test(t);
  if (!commandShaped && !settingIntent && !quotedCommand) return null;

  // อ้างคำพูด / ปฏิเสธ / เป็นคำถาม → ตอบวิธีแบบ deterministic ไม่เปลี่ยนค่า
  if (QUOTE_MARK.test(raw) || REPORTING_VERB.test(raw)) return "help";
  if (NEGATION.test(t)) return "help";
  if (QUESTION_HINT.test(raw)) return "help";

  if (OFF_RE.test(t)) return "off";
  if (ON_RE.test(t)) return "on";
  // "รับเตือน" / "เอาแจ้งเตือน" — กำกวมเกินกว่าจะเปิดให้เอง
  if (AMBIGUOUS_ON_RE.test(t)) return "help";

  // เป็นเรื่องตั้งค่าแจ้งเตือนแน่ ๆ แต่รูปประโยคไม่ชัด → help (ห้ามปล่อยเข้า AI)
  return "help";
}

