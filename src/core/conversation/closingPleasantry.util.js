/**
 * ข้อความปิดบทสนทนา (กบ 18 ส.ค.): "ขอบคุณ/ครับ/โชคดี/สาธุ" หลังจบเรื่อง = เงียบ
 * ไม่ต้องตอบทุก chat — เงียบไปจนกว่าลูกค้าจะส่งเรื่องใหม่/สแกนใหม่
 * (ประหยัด LLM call + ไม่รกแชท + ท่าทีนิ่งแบบอาจารย์)
 *
 * ใช้เฉพาะเลน idle เท่านั้น — state flows (ยืนยันวันเกิด/paywall ack) มี handler
 * ของตัวเองก่อนถึงจุดนี้อยู่แล้ว
 */

const PLEASANTRY_RES = [
  /^(ขอบคุณ|ขอบใจ|ขอบพระคุณ)(มาก|มากๆ|มากครับ|ครับ|ค่ะ|คับ|นะครับ|นะคะ|จ้า|ๆ|\s)*$/,
  /^(ครับ|ค่ะ|คับ|ครับผม|คร้าบ|จ้า|โอเค|โอเช|ok|okay|thx|thanks|thank you)(ครับ|ค่ะ|ผม|\s)*$/i,
  /^(โชคดี|ราตรีสวัสดิ์|ฝันดี|หลับฝันดี|บาย|สวัสดี)(ครับ|ค่ะ|นะครับ|นะคะ|นะ|\s)*$/,
  /^(สาธุ|อนุโมทนา)(ครับ|ค่ะ|สาธุ|\s)*$/,
  /^[🙏❤️😊😀🥰👍]+$/u,
];

/** @param {string} text @returns {boolean} true = ข้อความปิดบท ให้เงียบ */
export function isClosingPleasantry(text) {
  const t = String(text || "").trim();
  if (!t || t.length > 30) return false;
  return PLEASANTRY_RES.some((re) => re.test(t));
}
