/**
 * ธงสำหรับ template รายงาน/คลัง
 * @param {boolean} ownerProven ผู้ชมพิสูจน์แล้วว่าเป็นเจ้าของ (ดู ownerProof.util.js)
 * เจ้าของ → เปิดเต็มเสมอ ไม่ผูกกับการซื้อแพ็ก · ไม่ใช่เจ้าของ → ไม่เปิดคลังให้
 */
export function ownHistoryViewFlags(ownerProven) {
  const owner = ownerProven === true;
  return { accessFull: owner, memberAccess: owner };
}

