/**
 * intent "จัดชุด" (flow-role audit 26 ส.ค. — เคส 5: "จัดชุดพระให้หน่อยครับ" ไม่เข้า regex exact
 * แล้วตกไป paywall phrasing ที่มโน "ต้องสแกนก่อน 4 ชิ้น" ทั้งที่คลังมี 234 ชิ้น)
 *
 * ห้าม contains กว้าง — ต้องเป็นคำขอชัด: ประโยคสั้น (≤40) ขึ้นต้น/มีคำสั่ง "จัดชุด|ชุดวันนี้|ชุดพลัง"
 * และไม่มี negation/บริบทอื่น ("ยังไม่จัดชุด", "อย่าจัดชุด", "จัดชุดข้อมูล", เล่าเรื่อง)
 */
const CORE_RE = /(?:จัดชุด(?:พระ|พลัง|เครื่องราง|ให้)?|ชุดวันนี้|ชุดพลัง(?:วันนี้)?)/u;
const NEG_RE = /ยัง(?:ไม่|ไม่ได้)|อย่า|ไม่ต้อง|ไม่อยาก|ไม่เอา|เลิก|ยกเลิก|ห้าม/u;
/** "จัดชุด" ในความหมายอื่น */
const OTHER_MEANING_RE = /จัดชุด(?:ข้อมูล|เอกสาร|อาหาร|เสื้อ|ของขวัญ|โต๊ะ|สินค้า|ทัวร์)/u;
/** คำขอ/คำสั่ง (ประโยคขอทำ) */
const REQUEST_RE = /^(?:ขอ|ช่วย|รบกวน)?\s*(?:จัดชุด|ชุดวันนี้|ชุดพลัง)|(?:ให้หน่อย|หน่อย|ได้ไหม|ได้มั้ย|ที|ด้วย|ครับ|ค่ะ|คะ|จ้า)\s*$/u;

/** @param {string} text */
export function isSynergyRequest(text) {
  const t = String(text || "").trim();
  if (!t || t.length > 40) return false;
  if (!CORE_RE.test(t)) return false;
  if (NEG_RE.test(t)) return false;
  if (OTHER_MEANING_RE.test(t)) return false;
  // exact เดิมยังผ่านเสมอ
  if (/^(จัดชุด|ชุดวันนี้|ชุดพลัง|จัดชุดพลัง)$/u.test(t)) return true;
  // ประโยคสุภาพ: ต้องเป็นรูปคำขอ ไม่ใช่เล่าเรื่อง ("เมื่อวานอาจารย์จัดชุดให้เพื่อน")
  if (/เมื่อวาน|เพื่อน|เขา|เคย|ตอนนั้น|ที่แล้ว/u.test(t)) return false;
  return REQUEST_RE.test(t);
}
